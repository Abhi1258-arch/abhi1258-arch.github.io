# One-off content extraction for the portfolio site (Windows PowerShell 5.1 + Word).
# Re-run when the source documents change.
$ErrorActionPreference = 'Stop'
$Site = Split-Path $PSScriptRoot -Parent
$Research = "$env:USERPROFILE\OneDrive\Documents\Market Tracking\Research Projects"
$Journal  = "$env:USERPROFILE\OneDrive\Documents\Market Tracking\backup\Weekly Market Journal.docx"   # original, author-written entries only
$Quant    = "$env:USERPROFILE\quant_project\Indian-Market-Observatory\results"
Add-Type -AssemblyName System.IO.Compression.FileSystem

function JsString([string]$s){ ($s | ConvertTo-Json -Compress) }

# 1. research papers -> PDF
$papers = [ordered]@{
  'quantitative-investing.pdf' = 'Quantitative Investing Through Behavioral Finance.docx'
  'inflation-middle-class.pdf' = 'How Inflation Affects the Middle Class in India.docx'
  'upi-behavioural-finance.pdf' = 'Digital Payments and Behavioral Change- The Impact of UPI on Consumer Spending in India.docx'
  'monetary-policy-pivot-2024.pdf' = 'The Global Monetary Policy Pivot of 2024- Its Transmission to Global Markets and India.docx'
  'psychology-of-investors.pdf' = 'Psychology of Investors- Why People Make Irrational Investment Decisions.docx' }
$w = New-Object -ComObject Word.Application; $w.DisplayAlerts = 0
try {
  foreach ($k in $papers.Keys) { $d = $w.Documents.Open("$Research\$($papers[$k])", $false, $true); $d.ExportAsFixedFormat("$Site\assets\docs\$k", 17); "pdf: $k pages=$($d.ComputeStatistics(2))"; $d.Close(0) }

  # 2. weekly market journal -> structured entries
  $d = $w.Documents.Open($Journal, $false, $true)
  $entries = New-Object System.Collections.ArrayList; $cur = $null; $sec = $null
  foreach ($p in $d.Paragraphs) {
    $t = $p.Range.Text.Trim(); if (-not $t) { continue }
    if ($t -match '^Week:\s*(.+)$') { $cur = [ordered]@{ title = $Matches[1].Trim(); sections = New-Object System.Collections.ArrayList }; [void]$entries.Add($cur); $sec = $null; continue }
    if (-not $cur) { continue }
    $isHead = ($p.Style.NameLocal -match '^Heading') -or ($t.Length -lt 45 -and $t -notmatch '[.!?]$')
    if ($isHead) { $sec = [ordered]@{ heading = $t; paragraphs = New-Object System.Collections.ArrayList }; [void]$cur.sections.Add($sec) }
    else { if (-not $sec) { $sec = [ordered]@{ heading = ''; paragraphs = New-Object System.Collections.ArrayList }; [void]$cur.sections.Add($sec) }; [void]$sec.paragraphs.Add($t) }
  }
  $d.Close(0)
  $json = $entries | ConvertTo-Json -Depth 6
  [IO.File]::WriteAllText("$Site\assets\js\journal-data.js", "// Generated by tools/extract-content.ps1 from the Weekly Market Journal (author-written entries).`r`nwindow.JOURNAL = $json;`r`n", (New-Object Text.UTF8Encoding($false)))
  "journal entries: $($entries.Count)"
} finally { $w.Quit() }

# 3. backtest series -> JS
$m  = Import-Csv "$Quant\baseline_results\momentum_backtest.csv"
$mr = Import-Csv "$Quant\baseline_results\mean_reversion_backtest.csv"
$nf = Import-Csv "$Quant\baseline_results\nifty50_benchmark.csv"
$dm = Import-Csv "$Quant\baseline_results\drawdown_momentum.csv"; $dr = Import-Csv "$Quant\baseline_results\drawdown_mean_reversion.csv"; $dn = Import-Csv "$Quant\baseline_results\drawdown_nifty50.csv"
$tc = Import-Csv "$Quant\robustness_results\transaction_cost_sensitivity.csv"
$pm = Import-Csv "$Quant\baseline_results\performance_metrics.csv"
$obj = [ordered]@{
  months = @($m | ForEach-Object { $_.Month })
  value = [ordered]@{ momentum = @($m | % { [math]::Round([double]$_.PortfolioValue,2) }); meanReversion = @($mr | % { [math]::Round([double]$_.PortfolioValue,2) }); nifty = @($nf | % { [math]::Round([double]$_.PortfolioValue,2) }) }
  drawdown = [ordered]@{ momentum = @($dm | % { [math]::Round([double]$_.Drawdown,5) }); meanReversion = @($dr | % { [math]::Round([double]$_.Drawdown,5) }); nifty = @($dn | % { [math]::Round([double]$_.Drawdown,5) }) }
  costs = @($tc | % { [ordered]@{ bps = [int]$_.round_trip_bps; momentum = [math]::Round([double]$_.momentum_final_value,2); meanReversion = [math]::Round([double]$_.mean_reversion_final_value,2) } })
  metrics = @($pm | % { [ordered]@{ strategy = $_.Strategy; finalValue = [double]$_.'Final Value'; totalReturn = [double]$_.'Total Return'; cagr = [double]$_.CAGR; vol = [double]$_.'Annualized Volatility'; sharpe = [double]$_.'Sharpe Ratio (rf=0%)'; maxDD = [double]$_.'Maximum Drawdown'; best = [double]$_.'Best Month'; worst = [double]$_.'Worst Month'; pos = [int]$_.'Positive Months'; neg = [int]$_.'Negative Months'; winRate = [double]$_.'Win Rate' } })
}
$json = $obj | ConvertTo-Json -Depth 6 -Compress
[IO.File]::WriteAllText("$Site\assets\js\backtest-data.js", "// Generated by tools/extract-content.ps1 from the project's results/*.csv files.`r`nwindow.BACKTEST = $json;`r`n", (New-Object Text.UTF8Encoding($false)))
"backtest months: $($obj.months.Count)"

# 4. inflation paper figures, in document order
$z = [IO.Compression.ZipFile]::OpenRead("$Research\How Inflation Affects the Middle Class in India.docx")
$doc = (New-Object IO.StreamReader($z.GetEntry('word/document.xml').Open())).ReadToEnd()
$rels = (New-Object IO.StreamReader($z.GetEntry('word/_rels/document.xml.rels').Open())).ReadToEnd()
$ids = [regex]::Matches($doc, 'r:embed="([^"]+)"') | ForEach-Object { $_.Groups[1].Value }
$i = 0
foreach ($id in $ids) { $i++; $target = [regex]::Match($rels, "Id=`"$id`"[^>]*Target=`"([^`"]+)`"").Groups[1].Value; if (-not $target) { $target = [regex]::Match($rels, "Target=`"([^`"]+)`"[^>]*Id=`"$id`"").Groups[1].Value }
  $e = $z.GetEntry('word/' + $target); [IO.Compression.ZipFileExtensions]::ExtractToFile($e, "$Site\assets\img\inflation-fig-$i$([IO.Path]::GetExtension($target))", $true); "inflation fig $i <- $target" }
$z.Dispose()
